import os
from openai import OpenAI

client = OpenAI(
    api_key=os.environ["OPENAI_API_KEY"]
)

def summarize_article(title, abstract):

    prompt = f"""
Title:
{title}

Abstract:
{abstract}

Сделай краткое резюме исследования на простом русском языке, чтобы содержание понял студент третьего курса медицинского университета.

Если исследование посвящено эстетической медицине, уделяй особое внимание эффективности, безопасности, длительности эффекта и практическому применению ботулинотерапии, препаратов гиалуроновой кислоты, лазерных технологий, фототерапии, сфокусированного ультразвука и радиочастотных методов, а также их сравнению с другими методами лечения.

Не выводи оригинальное английское название статьи.

Все аббревиатуры расшифровывай на русском языке.

Строго соблюдай структуру ответа:

🧠 Главная мысль
<одна короткая фраза до 12 слов: главный вывод исследования>

🎯 Цель
<1–2 предложения>

🧪 Дизайн
<1–2 предложения>

📊 Основные результаты
<2–4 предложения>

💡 Практический вывод
<1–2 предложения, с акцентом на значение результатов для врача эстетической медицины>

Не добавляй другие разделы, вступления, комментарии или повтор названия статьи.

Общий объем — не более 150 слов.
"""

    response = client.chat.completions.create(
        model="gpt-5",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ]
    )

    return response.choices[0].message.content

